/**
 * The adversarial axes this corpus crosses.
 *
 * Every row names the axes it sits on, and `layeredClaimCorpus.test.ts` asserts
 * both that every axis is populated AND that the PAIRS § 21.9 asks about are
 * present - a floor on each axis separately is satisfied by a table that crosses
 * none of them.
 */
export type LayeredAxis =
  /** A copula contracted onto a NOUN subject: `Your meeting's booked`. § 21 class A. */
  | 'NOUN_CLITIC'
  /** A copula contracted onto a PRONOUN: `It's booked`, `I've booked`. The half that was always covered. */
  | 'PRONOUN_CONTRACTION'
  /** A different verb for the same effect: `I have pencilled you in`. */
  | 'PARAPHRASE'
  /** No completion verb at all: `you are all set`, `consider it done`, `הכל מסודר`. */
  | 'INDIRECT_CONFIRMATION'
  /** Hebrew first person, SINGULAR and PLURAL. § 21 class B. */
  | 'HEBREW_PERSON_NUMBER'
  /** A terminator is present: `.` or `!`. */
  | 'PUNCTUATION'
  /** No terminator at all, which is what a streamed clause looks like. */
  | 'NO_PUNCTUATION'
  /** Markdown: emphasis, a bullet, a heading, list numbering, a blockquote. */
  | 'MARKDOWN'
  /** A line break inside the sentence, LF or CRLF. */
  | 'LINE_BREAK'
  /** A confirmation or reference number the system never issued. */
  | 'INVENTED_REFERENCE'
  /** One turn, two languages. */
  | 'CODE_SWITCH';

