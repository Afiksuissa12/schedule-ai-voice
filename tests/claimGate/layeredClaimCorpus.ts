/**
 * How a model lays a sentence out.
 *
 * `render` takes the claim and returns it wrapped. Every wrapper is a
 * representational step, and § 19 is the record of one erasing a claim entirely:
 * `Your meeting is\nbooked for Thursday at 2pm.` was released to a caller while
 * the identical bytes with a space were withheld.
 */
export interface LayoutWrapper {
  readonly key: string;
  readonly axis: 'MARKDOWN' | 'LINE_BREAK';
  readonly render: (claim: string) => string;
  /**
   * Does the wrapper leave the base claim's when-phrase as a CONTIGUOUS substring?
   *
   * DECLARED RATHER THAN HOPED, because getting it wrong would be silent. A
   * wrapper that puts a line break inside `Thursday at 2pm` leaves the row with
   * no verbatim phrase to quote, and `src/agent/claimGate/semantic/schema.ts`
   * rejects an ungrounded quote as MALFORMED - so a double built from that row
   * would exercise a path production can never reach. Where this is `false` the
   * generated row carries `whenPhrase: null`, which is a legitimate verdict
   * (a verifier that read a completion and quoted no time) rather than a gap.
   */
  readonly keepsWhenPhrase: boolean;
}

