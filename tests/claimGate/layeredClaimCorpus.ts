/**
 * THE LAYERED ADVERSARIAL CORPUS - Mission 2F.
 *
 * WHY A SECOND CORPUS AND NOT MORE ROWS IN `claimGateCorpus.ts`
 * ---------------------------------------------------------------------------
 * `claimGateCorpus.ts` asks ONE question of every row: does
 * `detectMaterialClaims` see this? It is the deterministic layer's own corpus and
 * `docs/MISSION_2D_CLAIM_GATE_ASSURANCE.md` § 3.4 argues correctly that its
 * load-bearing half is the MISSES it records.
 *
 * This file asks a DIFFERENT question of every row, and it is the question
 * Mission 2F exists for: **which layer catches it, and does the layered pipeline
 * block it either way.** A row here is not "the detector should see this". A row
 * here is a claim plus a statement about WHICH of the two layers is expected to be
 * the one that sees it - and the pipeline must block it in both cases.
 *
 * So the two corpora are complementary and neither substitutes for the other:
 *
 *   claimGateCorpus.ts    -> is the LEXICON DETECTOR right about this sentence?
 *   layeredClaimCorpus.ts -> is the LAYERED GATE safe on this sentence, and by
 *                            which mechanism?
 *
 * THE ONE PROPERTY THIS FILE EXISTS TO MAKE FALSIFIABLE
 * ---------------------------------------------------------------------------
 * Eight successive independent QA rounds each found a phrasing shape the
 * deterministic lexicon did not recognise, and each leaked a false success claim
 * to a contact and persisted it with nothing behind it. The Founder's answer is a
 * semantic second layer that may only ADD suspicion. That answer is only worth
 * anything if it is FALSIFIABLE, which means three concrete things, all of them
 * asserted by `layeredClaimCorpus.test.ts` over this data:
 *
 *  1. DEFENCE IN DEPTH IS REAL, NOT NOMINAL. For the classes § 21 closed
 *     deterministically, BOTH layers must catch them. A class only one layer
 *     covers is not defence in depth, and `caughtBy: 'BOTH_LAYERS'` is how a row
 *     says so.
 *  2. THE SECOND LAYER GENUINELY ADDS. `caughtBy: 'SEMANTIC_ONLY_TODAY'` rows are
 *     wordings the REAL detector misses TODAY, on this tree, measured rather than
 *     assumed - and the test FAILS LOUDLY if one starts being caught, because a
 *     cross-layer proof whose premise quietly became false is a test that passes
 *     while proving nothing. See `SEMANTIC_ONLY_TODAY` below for the whole
 *     argument, which is the most important paragraph in this file.
 *  3. THE SECOND LAYER CANNOT CLEAR ANYTHING. Every row the detector flags is
 *     driven through the real `ClaimGate` with a verifier that says the text is
 *     clean, in all three shapes a model could say it, and must still be blocked.
 *     Asserted as a PROPERTY OVER THE WHOLE CORPUS rather than on one example.
 *
 * GENERATIVE WHERE THE AXIS IS MECHANICAL, REMEMBERED WHERE IT IS NOT
 * ---------------------------------------------------------------------------
 * `docs/MISSION_2D_CLAIM_GATE.md` § 16.6 is the standing lesson and § 21.9 sharpens
 * it into the test a reader can apply: **which PAIRS of axis values does this table
 * actually contain?** The `contracted` axis existed, both its values appeared, every
 * floor asking "are both values present?" passed - and every contracted row was a
 * subject PRONOUN, so the open half of the axis (an apostrophe on an arbitrary
 * NOUN) was invisible in 15,000 generated rows.
 *
 * So the axes below are generated as CROSSES, not as lists:
 *
 *   determiner x noun x predicate x punctuation      -> `CLITIC_CLAIMS`
 *   hebrew verb pair x NUMBER x punctuation          -> `HEBREW_PERSON_CLAIMS`
 *   layout wrapper x base claim                      -> `LAYOUT_CLAIMS`
 *   reference marker x invented token x language     -> `REFERENCE_CLAIMS`
 *   english claim x hebrew claim, both orders        -> `CODE_SWITCH_CLAIMS`
 *
 * and the axes that are VOCABULARY rather than morphology - paraphrases and
 * indirect confirmations - are listed by hand, because "a way of saying a thing
 * happened" is an open class and a generator over it would only multiply the
 * author's choice of idiom. § 17.8's closing subsection is the argument and it is
 * not reopened here.
 *
 * EVERY CLAIM IS PAIRED WITH AN HONEST CONTROL
 * ---------------------------------------------------------------------------
 * `LayeredCase.honestControl` is a truthful sentence built from the SAME words,
 * and the test requires it to stay clean at BOTH layers and to be released
 * BYTE-IDENTICAL through the real gate. Without that half this corpus would be
 * satisfied by a gate that blocked everything, which is the failure mode
 * `src/agent/claimGate/lexicon/en.ts` warns about: a gate somebody switches off.
 *
 * The controls are generated by the same generator as the claims, from the same
 * axis values, for one reason: a control somebody wrote separately is a control
 * that can drift away from the claim it is meant to localise.
 *
 * NOTHING HERE CALLS A MODEL, AND NOTHING HERE IS CUSTOMER-FACING SCRIPT
 * ---------------------------------------------------------------------------
 * Every verifier verdict in the test beside this file comes from the deterministic
 * doubles in `src/agent/claimGate/semantic/doubles.ts`. The strings below are
 * ADVERSARIAL SAMPLES - the sentences a gate must refuse, and the truthful ones it
 * must let through - which is what `tests/claimGate/` has always held and is why
 * `docs/MISSION_2D_CLAIM_GATE_ASSURANCE.md` § 3.1 argues this corpus must live
 * under `tests/` and not under `src/`.
 */
