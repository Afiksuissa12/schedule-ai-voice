/**
 * The effect families a row may claim.
 *
 * Written out rather than imported from the lexicon, for the reason
 * `tests/invariants/claimOracle.ts` gives about its own copy: a corpus that
 * imported the union under test would be kept in step with it by `tsc`, which is
 * the opposite of what an adversarial corpus wants.
 *
 * The five the brief requires are all here: BOOKING is `MEETING`, CALLBACK,
 * RESCHEDULE, CANCELLATION, and SENDING is `MESSAGE`. `ANY` is the completion
 * with nothing named - `all set`, `סגרתי` - which is its own class because no
 * family-specific effect can ever support it.
 */
export type LayeredFamily = 'MEETING' | 'RESCHEDULE' | 'CANCELLATION' | 'CALLBACK' | 'MESSAGE' | 'ANY';

export const LAYERED_FAMILIES: readonly LayeredFamily[] = [
  'MEETING',
  'RESCHEDULE',
  'CANCELLATION',
  'CALLBACK',
  'MESSAGE',
  'ANY',
];

export type LayeredMode = 'COMPLETED' | 'COMMITTED';

/** Is this one of the six families this corpus claims? Narrows, so no cast is needed. */
export function isLayeredFamily(family: string): family is LayeredFamily {
  return (LAYERED_FAMILIES as readonly string[]).includes(family);
}

/**
 * WHICH LAYER IS EXPECTED TO SEE THIS ROW.
 *
 * `BOTH_LAYERS` - defence in depth, and the only value that proves it. The
 * deterministic detector must produce a claim in one of the row's declared
 * families, AND a semantic double built from the row's declaration must produce
 * one too, AND the union must tag it `BOTH`.
 *
 * `SEMANTIC_ONLY_TODAY` - AND THE WORD `TODAY` IS LOAD-BEARING. This is a wording
 * the REAL deterministic detector misses on THIS tree, measured by running it in
 * `layeredClaimCorpus.test.ts` rather than asserted here. Two things follow, and
 * the second is the one that stops this corpus rotting:
 *
 *  - the row is the cross-layer proof the Founder asked for: a claim only the
 *    second layer sees, blocked by the layered pipeline;
 *  - **if the deterministic layer STARTS catching it, the test FAILS, loudly, by
 *    name, and tells the author to move the row to `BOTH_LAYERS` and find a new
 *    one.** That is deliberate and it is the opposite of the usual instinct. A
 *    detector improvement is good news, and a cross-layer proof standing on a
 *    premise that has quietly become false is a test that passes while proving
 *    nothing - which is, precisely and eight times over, how this gate got here
 *    (`docs/MISSION_2D_CLAIM_GATE.md` § 16.6, § 17.2, § 21.2). A green suite is
 *    not the goal; a suite whose green means something is.
 *
 * The alternative - `DetectClaimsOptions.lexicons: []`, the blind seam
 * `tests/agent/claimGateSemanticPipeline.test.ts` uses - proves the PIPELINE
 * shape and deliberately proves nothing about the real detector's real coverage.
 * Both are wanted and this file is the other one: these are wordings a model
 * really writes, missed by the detector that really ships.
 */
export type LayeredCaughtBy = 'BOTH_LAYERS' | 'SEMANTIC_ONLY_TODAY';

export interface LayeredCase {
  /** Quoted in every failure message. Must identify the row without the text. */
  readonly name: string;
  /** The adversarial sentence. A gate must refuse this over an empty ledger. */
  readonly text: string;
  readonly language: 'en' | 'he' | 'mixed';
  readonly axes: readonly LayeredAxis[];
  /**
   * The families a reader would accept for this claim.
   *
   * A SET rather than one value, and the reason is a real property of the
   * detector rather than hedging. `Your callback's booked for Thursday at 2pm.`
   * is read as CALLBACK, not MEETING, because `callback is booked` is its own
   * declared frame and the longest match across families wins - which is § 8
   * limit 9's mechanism seen from the coverage side. `Your meeting's booked` on
   * the identical predicate is MEETING. So the noun CAN move the family, for
   * exactly the nouns that are themselves lexicon tokens, and a row over
   * `callback` declares both.
   *
   * Asserted as membership. `familiesDeclaredButNeverSeen` in the self-test is
   * the guard against a set so wide it asserts nothing.
   */
  readonly families: readonly LayeredFamily[];
  readonly mode: LayeredMode;
  readonly caughtBy: LayeredCaughtBy;
  /**
   * A TRUTHFUL sentence built from the same words, which must stay clean at both
   * layers and be released BYTE-IDENTICAL through the real gate.
   *
   * Generated by the same generator as `text` wherever `text` is generated, so
   * the two cannot drift apart.
   */
  readonly honestControl: string;
  /**
   * The day-or-hour phrase this text names, VERBATIM, or `null`.
   *
   * Verbatim because that is what the semantic port requires
   * (`src/ports/claimVerifier.ts`: every quoted field must occur in the text or
   * the whole output is MALFORMED), and because a double whose output production
   * would reject is a double testing a path production cannot reach.
   */
  readonly whenPhrase: string | null;
  /** The identifier this text reads out, VERBATIM, or `null`. */
  readonly identifier: string | null;
  /** Why a reader of the sentence says it asserts this. Mandatory prose. */
  readonly why: string;
}

