// ---------------------------------------------------------------------------
// 13. THE SELF-TEST
// ---------------------------------------------------------------------------

export interface LayeredCorpusSelfTestResult {
  readonly failures: readonly string[];
  /** Rows whose declared layer really is the layer that sees them. */
  readonly defenceInDepthChecked: number;
  readonly semanticOnlyChecked: number;
  readonly honestControlsChecked: number;
  /**
   * The recorded false positives that have STOPPED being false positives.
   *
   * Reported as its own list for the same reason
   * `semanticOnlyNowCaughtDeterministically` is: it is good news, and it must
   * still fail, because a recorded limitation nobody notices getting fixed is a
   * document that has started lying.
   */
  readonly knownFalsePositivesNowClean: readonly string[];
  /**
   * Rows declared `SEMANTIC_ONLY_TODAY` that the deterministic layer has STARTED
   * catching.
   *
   * GOOD NEWS THAT MUST FAIL A TEST. See `LayeredCaughtBy`. Reported as its own
   * number rather than folded into `failures` so the report can say plainly that
   * the detector improved and a cross-layer proof needs a new premise.
   */
  readonly semanticOnlyNowCaughtDeterministically: readonly string[];
  /** Honest controls the deterministic layer flagged. A false positive. */
  readonly honestControlsFlagged: readonly string[];
  /** Every axis that appears on at least one row. */
  readonly axesExercised: readonly LayeredAxis[];
  /** Every `axis|axis` pair that appears together on at least one row. § 21.9's test. */
  readonly axisPairsExercised: readonly string[];
  readonly familiesExercised: readonly LayeredFamily[];
  /** Families a row DECLARED and no row ever produced. A set so wide it asserts nothing. */
  readonly familiesDeclaredButNeverSeen: readonly LayeredFamily[];
  readonly languagesExercised: readonly string[];
  readonly modesExercised: readonly LayeredMode[];
  /** `family/mode/locale` triples the deterministic layer really produced. */
  readonly detectorTriples: readonly string[];
}

/**
 * Run the deterministic half of the corpus.
 *
 * Returns rather than throws, exactly as `runClaimGateSelfTest` does and for the
 * same reason: a caller wants every failure at once. The LAYERED half needs a
 * `ClaimGate`, which is async and needs a ledger, so it lives in the test file
 * beside this one - this function is the part that is a pure function of the
 * corpus and the detector.
 */
export function runLayeredCorpusSelfTest(): LayeredCorpusSelfTestResult {
  const failures: string[] = [];
  const axes = new Set<LayeredAxis>();
  const axisPairs = new Set<string>();
  const families = new Set<LayeredFamily>();
  const declaredFamilies = new Set<LayeredFamily>();
  const languages = new Set<string>();
  const modes = new Set<LayeredMode>();
  const triples = new Set<string>();
  const nowCaught: string[] = [];
  const flaggedControls: string[] = [];

  let defenceInDepthChecked = 0;
  let semanticOnlyChecked = 0;

  for (const entry of LAYERED_CLAIM_CORPUS) {
    for (const axis of entry.axes) axes.add(axis);
    // Every unordered pair of axes on this row. § 21.9's test is about PAIRS: a
    // floor on each dimension separately is satisfied by a table that crosses
    // none of them.
    const sorted = [...new Set(entry.axes)].sort();
    for (let i = 0; i < sorted.length; i += 1) {
      for (let j = i + 1; j < sorted.length; j += 1) axisPairs.add(`${sorted[i]}|${sorted[j]}`);
    }
    for (const family of entry.families) declaredFamilies.add(family);
    languages.add(entry.language);
    modes.add(entry.mode);

    // Every quoted field must really be in the text, or a double built from this
    // row would be MALFORMED in production and the row would test nothing.
    if (entry.whenPhrase !== null && !entry.text.includes(entry.whenPhrase)) {
      failures.push(
        `"${entry.name}" declares whenPhrase ${JSON.stringify(entry.whenPhrase)}, which is NOT a substring of ` +
          `its own text. src/agent/claimGate/semantic/schema.ts rejects an ungrounded quote as MALFORMED, so a ` +
          'double built from this row would exercise a path production can never reach.',
      );
    }
    if (entry.identifier !== null && !entry.text.includes(entry.identifier)) {
      failures.push(
        `"${entry.name}" declares identifier ${JSON.stringify(entry.identifier)}, which is not in its own text.`,
      );
    }
    if (entry.why.trim().length < 20) {
      failures.push(
        `"${entry.name}" carries no reasoning in its \`why\`. An unexplained adversarial row cannot be ` +
          'reviewed, which is how a wrong row would survive.',
      );
    }
    if (entry.families.length === 0) {
      failures.push(`"${entry.name}" declares no family, so nothing about it can be asserted.`);
    }

    const claims = detectMaterialClaims(entry.text);
    for (const claim of claims) {
      // Narrowed rather than cast: `RECORD` and `HANDOVER` are real lexicon
      // families that this corpus does not claim, and folding one into
      // `familiesExercised` would make that field say something false.
      if (isLayeredFamily(claim.family)) families.add(claim.family);
      triples.add(`${claim.family}/${claim.mode}/${claim.locale}`);
    }

    if (entry.caughtBy === 'BOTH_LAYERS') {
      defenceInDepthChecked += 1;
      if (claims.length === 0) {
        failures.push(
          `DEFENCE IN DEPTH BROKEN: "${entry.name}" is declared to be caught by BOTH layers and the ` +
            'DETERMINISTIC layer found nothing in it. Either a lexicon rule stopped firing - which is a ' +
            'regression of exactly the kind eight QA rounds found - or this row should be declared ' +
            `SEMANTIC_ONLY_TODAY. Text: ${JSON.stringify(entry.text)}`,
        );
      } else if (!claims.some((claim) => isLayeredFamily(claim.family) && entry.families.includes(claim.family))) {
        failures.push(
          `"${entry.name}" was detected as ${claims.map((claim) => claim.family).join(', ')} and declares ` +
            `${entry.families.join('/')}. A claim reconciled against the wrong family is reconciled against ` +
            'the wrong effect, which is § 8 limit 9 seen from the coverage side.',
        );
      }
    } else {
      semanticOnlyChecked += 1;
      if (claims.length > 0) {
        // GOOD NEWS, AND IT MUST FAIL. See `LayeredCaughtBy`.
        nowCaught.push(
          `"${entry.name}" is declared SEMANTIC_ONLY_TODAY and the DETERMINISTIC layer now catches it as ` +
            `${claims.map((claim) => `${claim.family}/${claim.matchedForm}`).join(', ')}. That is an ` +
            'IMPROVEMENT and it makes this cross-layer proof VACUOUS: move the row to BOTH_LAYERS, record ' +
            'the closure, and declare a new SEMANTIC_ONLY_TODAY row so the proof keeps a live premise. ' +
            `Text: ${JSON.stringify(entry.text)}`,
        );
      }
    }
  }

  // ---- the honest half ---------------------------------------------------
  for (const control of ALL_HONEST_CONTROLS) {
    const claims = detectMaterialClaims(control.text);
    if (claims.length > 0) {
      flaggedControls.push(
        `${JSON.stringify(control.text)} -> ${claims
          .map((claim) => `${claim.family}/${claim.matchedForm}`)
          .join(', ')} (${control.why})`,
      );
    }
  }
  if (flaggedControls.length > 0) {
    failures.push(
      `${flaggedControls.length} of ${ALL_HONEST_CONTROLS.length} HONEST CONTROLS were flagged by the ` +
        'deterministic layer. A gate that blocks truthful sentences is a gate somebody switches off, and then ' +
        'the § 6.5.4 defect is back. Every one of these is either a genuine false positive or a control that ' +
        'was written wrong:\n' +
        flaggedControls.map((line) => `      ${line}`).join('\n'),
    );
  }

  // ---- the recorded false positives are STILL false positives ------------
  const nowClean: string[] = [];
  for (const entry of KNOWN_CONTROL_FALSE_POSITIVES) {
    if (detectMaterialClaims(entry.text).length === 0) {
      nowClean.push(
        `${JSON.stringify(entry.text)} is recorded as a FALSE POSITIVE (${entry.flaggedAs}) and is now CLEAN. ` +
          'That is an improvement and it must not land silently: remove the entry from ' +
          'KNOWN_CONTROL_FALSE_POSITIVES, move the wording into the honest controls, and record what closed ' +
          `it. The recorded cause was: ${entry.cause}`,
      );
    }
  }
  if (nowClean.length > 0) failures.push(...nowClean);

  const declaredNeverSeen = [...declaredFamilies].filter((family) => !families.has(family));

  return {
    failures,
    defenceInDepthChecked,
    semanticOnlyChecked,
    honestControlsChecked: ALL_HONEST_CONTROLS.length,
    knownFalsePositivesNowClean: nowClean,
    semanticOnlyNowCaughtDeterministically: nowCaught,
    honestControlsFlagged: flaggedControls,
    axesExercised: [...axes].sort(),
    axisPairsExercised: [...axisPairs].sort(),
    familiesExercised: [...families].sort(),
    familiesDeclaredButNeverSeen: declaredNeverSeen.sort(),
    languagesExercised: [...languages].sort(),
    modesExercised: [...modes].sort(),
    detectorTriples: [...triples].sort(),
  };
}
